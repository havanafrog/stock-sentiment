/**
 * 이 글이 공포를 담고 있는가. 참/거짓만 돌려준다.
 *
 * 알려진 한계: 앞에 붙는 부정어("안 무섭다")는 걸러내지만, 한국어 부정이 뒤에 오는
 * 경우("손절 안 했다")는 놓친다. 그래도 z-score 로 보기 때문에 크게 문제되지 않는다 —
 * 기준선을 **같은 채점기**로 계산하므로 이런 체계적 오탐은 평균에 그대로 섞여
 * 차감된다. 우리가 보는 건 절대 수준이 아니라 평소 대비 변화다.
 */
window.hasFear = function (text) {
  if (!text) return false;
  for (const w of window.LEX_FEAR) {
    let from = 0, idx;
    while ((idx = text.indexOf(w, from)) !== -1) {
      const lead = text.slice(Math.max(0, idx - 4), idx);
      if (!window.LEX_NEGATORS.some(n => lead.includes(n))) return true;
      from = idx + w.length;
    }
  }
  return false;
};

// -1 ~ +1. 사전에 걸린 단어가 하나도 없으면 0(중립).
window.scoreWith = function (text, lex) {
  if (!text) return 0;
  let s = 0, hits = 0;
  const scan = (dict, sgn) => {
    for (const w in dict) {
      let from = 0, idx;
      while ((idx = text.indexOf(w, from)) !== -1) {
        // 직전 4글자 안에 부정어가 있으면 방향을 뒤집는다
        const lead = text.slice(Math.max(0, idx - 4), idx);
        const flipped = window.LEX_NEGATORS.some(n => lead.includes(n)) ? -1 : 1;
        s += sgn * flipped * dict[w];
        hits++;
        from = idx + w.length;
      }
    }
  };
  scan(lex.pos, 1);
  scan(lex.neg, -1);
  if (!hits) return 0;
  return Math.max(-1, Math.min(1, s / (hits * 2.2)));
};

// ── 공포지수 ────────────────────────────────────────────────
// 공포어 비율은 종목마다 평소 수준이 2배씩 다르고(SNDK 3.7% ↔ MUU 7.1%)
// 같은 종목도 시간대마다 2배 차이난다. 그래서 절대 비율이 아니라
// 그 종목·그 맥락의 평소 대비 몇 표준편차인지를 0~100 으로 편다.
//
//   z ±2.5 에서 포화. 90 = z 2 = 실시간 카드가 붉어지는 조건과 같은 지점.
window.FEAR_ALERT = 90;

window.fearIndex = function (ratio, base) {
  if (ratio === null || ratio === undefined) return null;
  if (!base || !base.sd) return null;          // sd 0 이면 z 가 무한대가 된다
  const z = (ratio - base.mean) / base.sd;
  return Math.max(0, Math.min(100, 50 + 20 * z));
};

// ── 공포 강도 (계수 기반) ───────────────────────────────────
// 비율은 표본이 있어야 말이 된다. 1분봉은 글이 중앙값 2건이라 비율이
// 0% / 50% / 100% 셋뿐이고, 문턱을 걸면 97%가 빈칸이 된다.
//
// 그래서 짧은 구간에서는 "몇 %가 공포냐"가 아니라 "공포 글이 몇 개 왔냐"를 잰다.
// 평소 분당 0.6건인데 15건이 오는 순간, 그게 사건이다.
//
//   z = (그 구간 공포 글 수 − 그 종목·그 ET 시각의 평균) / 표준편차
//
// 표준편차는 포아송 √λ 가 아니라 실측값을 쓴다. 글은 몰려서 오기 때문에
// 실제 분산이 포아송보다 크다(SNDK ET 10시: 평균 0.60, 표준편차 1.00).
window.fearIntensity = function (count, base) {
  if (count === null || count === undefined) return null;
  if (!base || !base.sd) return null;
  const z = (count - base.mean) / base.sd;
  return Math.max(0, Math.min(100, 50 + 20 * z));
};

// ── 곡소리 ──────────────────────────────────────────────────
// 감정 평균은 잘 안 움직인다. 22만 건에서 실측 ±0.05 안쪽이라
// 게이지로 만들면 늘 가운데 붙어 있다. 평균이 아니라 개수로 센다.
//
// 곡소리 = 그 글이 부정이냐. 공포와 다르다 —
//   공포:   "무섭다·손절·물렸" 처럼 겁먹은 말
//   곡소리: 겁이 아니어도 나쁘게 말하는 것 전부 (욕·조롱·하락·자조)
// 그래서 공포지수보다 넓고 잘 움직인다.
window.isWail = function (text) {
  return window.scoreWith(text, window.LEX_DEFAULT) < 0;
};

