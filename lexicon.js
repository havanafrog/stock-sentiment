/**
 * 이 글이 공포를 담고 있는가. 참/거짓만 돌려준다.
 *
 * 알려진 한계: 앞에 붙는 부정어("안 무섭다")는 걸러내지만, 한국어 부정이 뒤에 오는
 * 경우("손절 안 했다")는 놓친다. 그래도 z-score 로 보기 때문에 크게 문제되지 않는다 —
 * 기준선을 **같은 채점기**로 계산하므로 이런 체계적 오탐은 평균에 그대로 섞여
 * 차감된다. 우리가 보는 건 절대 수준이 아니라 평소 대비 변화다.
 */
window.hasFear = function (raw) {
  const text = window.normalize(raw);
  if (!text) return false;
  for (const w of window.LEX_FEAR) {
    let from = 0, idx;
    while ((idx = text.indexOf(w, from)) !== -1) {
      const lead = text.slice(Math.max(0, idx - 4), idx);
      if (!window.LEX_NEGATORS.some(n => lead.includes(n))) return true;
      from = idx + w.length;
    }
  }
  return false;
};

// 글쓴이들은 필터를 피하려고 글자 사이에 숫자·점·별표를 끼워 넣는다.
//   시1발  ㅆ.ㅂ  ㅁ2친  병1신  ㅅ ㅂ
// 그대로 두면 사전이 통째로 못 잡는다. 실측으로 되살아나는 양이 크다:
//   시발 39건 → 834건 · ㅅㅂ 110 → 858 · 병신 2 → 333 · 지랄 6 → 271
//
// 한글 글자 사이에 낀 것만 지운다. 낱말 경계의 숫자·기호는 건드리지 않는다 —
// "1600 물렸다" 의 1600 을 지우면 안 되고, 공백을 다 지우면 엉뚱한 말이 붙는다.
window.normalize = function (text) {
  if (!text) return text;
  return String(text).replace(/([가-힣ㄱ-ㅎ])[0-9.@*^_\-\s]{1,2}(?=[가-힣ㄱ-ㅎ])/g, '$1');
};
// -1 ~ +1. 사전에 걸린 단어가 하나도 없으면 0(중립).
